async def log_outcome_created(
    user_id: str, 
    email: str, 
    agent_id: str, 
    outcome_id: str, 
    result: str,
    submitter_type: str = "self"
):
    """Log outcome submission"""
    actor_type = "user" if submitter_type == "self" else "system"
    await emit_audit_log(
        event_type="outcome.logged",
        actor_type=actor_type,
        actor_id=user_id,
        actor_email=email,
        metadata={
            "agent_id": agent_id,
            "outcome_id": outcome_id,
            "result": result,
            "submitter_type": submitter_type
        },
        description=f"Outcome logged: {result} for agent {agent_id[:8]}..."
    )


async def log_agent_flagged(
    user_id: str, 
    email: str, 
    agent_id: str, 
    flag_id: str, 
    reason: str,
    outcome_id: Optional[str] = None
):
    """Log agent/outcome flagging"""
    target = f"outcome {outcome_id[:8]}..." if outcome_id else f"agent {agent_id[:8]}..."
    await emit_audit_log(
        event_type="agent.flagged",
        actor_type="user",
        actor_id=user_id,
        actor_email=email,
        metadata={
            "agent_id": agent_id,
            "flag_id": flag_id,
            "outcome_id": outcome_id,
            "reason": reason
        },
        description=f"Flag created on {target}: {reason}"
    )


async def log_agent_public_toggled(
    user_id: str,
    email: str,
    agent_id: str,
    agent_name: str,
    is_public: bool
):
    """Log agent public visibility toggle"""
    status = "public" if is_public else "private"
    await emit_audit_log(
        event_type="agent.public_toggled",
        actor_type="user",
        actor_id=user_id,
        actor_email=email,
        metadata={
            "agent_id": agent_id,
            "agent_name": agent_name,
            "is_public": is_public
        },
        description=f"Agent '{agent_name}' set to {status}"
    )
