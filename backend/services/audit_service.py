"""
Audit Log Service

Centralized service for emitting audit log entries.
Keeps audit logging simple and consistent across the application.
"""
import uuid
from datetime import datetime, timezone
from typing import Optional, Dict, Any

from core.database import db


async def emit_audit_log(
    event_type: str,
    actor_type: str = "system",
    actor_id: Optional[str] = None,
    actor_email: Optional[str] = None,
    metadata: Optional[Dict[str, Any]] = None,
    description: Optional[str] = None
):
    """
    Emit an audit log entry.
    
    Args:
        event_type: Type of event (e.g., "user.signup", "agent.created")
        actor_type: Who performed the action ("user", "admin", "system")
        actor_id: ID of the actor (None for system events)
        actor_email: Email of the actor (for display purposes)
        metadata: Additional context as JSON-serializable dict
        description: Human-readable description of the event
    """
    log_entry = {
        "id": str(uuid.uuid4()),
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "actor_type": actor_type,
        "actor_id": actor_id,
        "actor_email": actor_email,
        "event_type": event_type,
        "metadata": metadata or {},
        "description": description
    }
    
    await db.audit_logs.insert_one(log_entry)
    return log_entry


# Convenience functions for common events

async def log_user_signup(user_id: str, email: str):
    """Log a user signup event"""
    await emit_audit_log(
        event_type="user.signup",
        actor_type="user",
        actor_id=user_id,
        actor_email=email,
        metadata={"user_id": user_id, "email": email},
        description=f"New user signed up: {email}"
    )


async def log_user_login(user_id: str, email: str):
    """Log a user login event"""
    await emit_audit_log(
        event_type="user.login",
        actor_type="user",
        actor_id=user_id,
        actor_email=email,
        metadata={"user_id": user_id},
        description=f"User logged in: {email}"
    )


